function rustConstant(source, name) {
  const match = source.match(new RegExp(`pub const ${name}: [^=]+ = ([^;]+);`));
  if (!match?.[1]) throw new Error(`missing Rust constant ${name}`);
  return match[1].trim().replaceAll("_", "");
}

function selectedOption(id) {
  const select = html.match(new RegExp(`<select id="${id}">([\\s\\S]*?)</select>`))?.[1];
  const value = select?.match(/<option value="([^"]+)" selected>/)?.[1];
  if (!value) throw new Error(`missing selected option for ${id}`);
  return value;
}

function inputValue(id) {
  const value = html.match(new RegExp(`<input id="${id}"[^>]*value="([^"]+)"`))?.[1];
  if (!value) throw new Error(`missing input value for ${id}`);
  return value;
}

function typescriptConstant(source, name) {
  const match = source.match(new RegExp(`export const ${name} = ([^;]+);`));
  if (!match?.[1]) throw new Error(`missing TypeScript constant ${name}`);
  return match[1].trim().replaceAll("_", "");
}

function configDigest(registerCount) {
  const bytes = [];
  const buffer = new ArrayBuffer(8);
  const view = new DataView(buffer);
  const append = (length = 8) => bytes.push(...new Uint8Array(buffer, 0, length));
  view.setUint16(0, Number(rustConstant(config, "SCIENTIFIC_CONFIG_VERSION")), true);
  append(2);
  bytes.push(Number(inputValue("kmer-length")), 1); // ntHash2
  view.setBigUint64(0, 0n, true);
  append();
  view.setBigUint64(0, BigInt(registerCount), true);
  append();
  bytes.push(
    Number(rustConstant(config, "DEFAULT_B_BITS")),
    Number(rustConstant(config, "DEFAULT_VERIFICATION_BITS")),
    2, // verified-winner OPH
    Number(rustConstant(config, "DEFAULT_HLL_PRECISION")),
    1, // half-window expansion
    1, // containment kth-root ANI
  );
  view.setBigUint64(0, 0n, true);
  append();
  view.setFloat64(0, Number(rustConstant(adaptive, "DEFAULT_ANI_FLOOR")), true);
  append();
  view.setFloat64(
    0,
    Number(rustConstant(adaptive, "DEFAULT_MATCH_DETECTION_PROBABILITY")),
    true,
  );
  append();
  view.setUint16(0, 65_535, true);
  append(2);
  view.setUint16(0, 10_000, true);
  append(2);
  let digest = 0xcbf2_9ce4_8422_2325n;
  for (const byte of bytes) {
    digest ^= BigInt(byte);
    digest = BigInt.asUintN(64, digest * 0x0000_0100_0000_01b3n);
  }
  return digest.toString(16).padStart(16, "0");
}

